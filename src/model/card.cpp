struct card{
	char name[50];
	int number;
	char instruction[200];
};
struct card *card_create(const char *name,int number){
	struct card *card = (struct card *)malloc(sizeof(struct card));
	if(card == NULL) return NULL;
	
	strcpy(card->name , name);
	card->number = number;
	
	switch(number){
		case 1: snprintf(card->instruction, sizeof(card->instruction), "Swap both players' positions"); break;
		case 2: snprintf(card->instruction, sizeof(card->instruction), "Take all houses from the other player"); break;
		case 3: snprintf(card->instruction, sizeof(card->instruction), "Average both players' cash"); break;
		case 4: snprintf(card->instruction, sizeof(card->instruction), "Upgrade all houses owned by this player"); break;
	}
	
	return card;
};

void card_destroy(struct card *card){
	free(card);
}

char *card_get_name(struct card *card){
	return card->name;
}

int card_get_number(struct card *card){
	return card->number;
}

char *card_get_instruction(struct card *card){
	return card->instruction;
}
